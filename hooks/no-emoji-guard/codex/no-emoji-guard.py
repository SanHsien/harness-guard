VS16 = 0xFE0F

# Obsidian Tasks plugin 功能標記（僅在待辦行 - [ ] / - [x] 上放行）
TASK_MARKERS = re.compile(
    "[" +
    "\U0001F4C5"  # 到期日 due
    "\U0001F4C6"  # 排程 scheduled
    "\U0001F6EB"  # 開始 start
    "\u2705"      # 完成 done
    "\u274C"      # 取消 cancelled
    "\u23F3"      # 進行中
    "\U0001F501"  # 重複 recurring
    "\u23EB\u23EC\U0001F53C\U0001F53D"  # 優先權 priority
    "\U0001F525\u23F1\U0001F534"          # daily note 慣例符號
    "]\uFE0F?"
)



def _in(cp, table):
    for a, b in table:
        if a <= cp <= b:
            return True
        if cp < a:
            return False
    return False


def find_emoji(text):
    """回傳 [(字元, 位置)]，依上述兩條判準。"""
    hits = []
    n = len(text)
    for i, ch in enumerate(text):
        cp = ord(ch)
        if _in(cp, EMOJI_PRESENTATION):
            hits.append((ch, i))
        elif _in(cp, EXT_PICTOGRAPHIC) and i + 1 < n and ord(text[i + 1]) == VS16:
            hits.append((ch + text[i + 1], i))
    return hits


# 想整棵子樹都不要擋（例如 Obsidian vault，那裡的符號是功能語法不是裝飾），
# 把路徑片段加進來。例：EXEMPT_PATH_SUBSTRINGS = ["/my-notes/", "/vault/"]
EXEMPT_PATH_SUBSTRINGS = []


def _exempt_subtree(path):
    return any(s and s in path for s in EXEMPT_PATH_SUBSTRINGS)


def collect(tool_input):
    """把這次寫入的所有文字內容湊起來（各 tool 欄位不同）。"""
    parts = []
    for key in ("content", "new_string", "prompt", "patch", "input"):
        v = tool_input.get(key)
        if isinstance(v, str):
            parts.append(v)
    for edit in tool_input.get("edits", []) or []:
        if isinstance(edit, dict) and isinstance(edit.get("new_string"), str):
            parts.append(edit["new_string"])
    return "\n".join(parts)


def main():
    try:
        payload = json.load(sys.stdin)
    except Exception:
        sys.exit(0)

    tool_name = payload.get("tool_name") or ""
    if tool_name not in {"Write", "Edit", "MultiEdit", "apply_patch", "Bash", "exec", "shell"}:
        sys.exit(0)

    tool_input = payload.get("tool_input") or {}
    if isinstance(tool_input, str):
        tool_input = {"patch": tool_input}

    exempt_path = r"(逐字稿|transcript|/_archive/|\.srt$|\.vtt$)"

    if tool_name in {"Bash", "exec", "shell"}:
        # codex exec 模式把 apply_patch 當 shell 指令跑，patch 內文在 command 裡。
        # 只掃新增行——掃整段會把「移除 emoji」的 patch 也擋下。
        command = tool_input.get("command") or ""
        if "apply_patch" not in command:
            sys.exit(0)
        cwd = payload.get("cwd") or ""
        patch_paths = [
            p if os.path.isabs(p) else os.path.join(cwd, p)
            for p in re.findall(r"^\*\*\* (?:Add|Update|Delete) File: (.+)$", command, flags=re.M)
        ]
        if patch_paths and all(
            re.search(exempt_path, p) or _exempt_subtree(p) for p in patch_paths
        ):
            sys.exit(0)
        text = "\n".join(
            line[1:] for line in command.splitlines()
            if line.startswith("+") and not line.startswith("+++")
        )
    else:
        path = tool_input.get("file_path") or tool_input.get("path") or ""

        # 逐字稿、原始外部輸入原樣歸檔，不擋
        if re.search(exempt_path, path):
            sys.exit(0)

        # 整棵子樹放行（見檔頭 EXEMPT_PATH_SUBSTRINGS）。典型用途是 Obsidian vault：
        # 那裡的到期日、完成、進行中符號是 Tasks plugin 的功能語法而非裝飾，
        # 清掉會弄壞待辦追蹤。
        if _exempt_subtree(path):
            sys.exit(0)

        text = collect(tool_input)

    if not text:
        sys.exit(0)

    # 任何檔案裡的 Obsidian 待辦行（- [ ] / - [x]）同樣放行上述 Tasks plugin 標記
    text = re.sub(
        r"^(\s*[-*]\s*\[[ xX/\-]\].*)$",
        lambda m: TASK_MARKERS.sub("", m.group(1)),
        text,
        flags=re.M,
    )

    hits = find_emoji(text)
    if not hits:
        sys.exit(0)

    uniq = []
    for ch, _ in hits:
        if ch not in uniq:
            uniq.append(ch)

    sys.stderr.write(
        "NO-EMOJI GUARD：這次寫入含 %d 個 emoji%s——%s\n"
        "全域規則：文件、投影片、程式碼註解、commit message 一律禁 emoji。\n"
        "請移除後重寫。需要狀態符號請改用排版記號（✓ ✕ → ←）或純文字（完成／待辦／注意）。\n"
        "例外（逐字稿、外部原檔歸檔）已自動放行，本次不屬於此類。\n"
        % (len(hits), "（去重後 %d 種）" % len(uniq) if len(uniq) != len(hits) else "", " ".join(uniq))
    )
    sys.exit(2)


if __name__ == "__main__":
    main()
